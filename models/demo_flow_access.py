class DemoFlowCalendar(models.Model):
    _inherit = 'calendar.event'

    def write(self, vals):
        if vals.get('res_id'):
            for event in self:
                if vals.get('res_model', event.res_model) == 'crm.lead':
                    check_demo(self.env['crm.lead'].browse(vals['res_id']))
        return write_child(self, vals, super().write)

    @api.model_create_multi
    def create(self, vals_list):
        # Calendar tag synchronization uses sudo, so validate CRM ownership
        # before allowing an event to be associated through native res_id.
        for vals in vals_list:
            model = vals.get('res_model', self.env.context.get('default_res_model'))
            lead_id = vals.get('crm_lead_id', self.env.context.get('default_crm_lead_id'))
            if model == 'crm.lead':
                lead_id = vals.get('res_id', self.env.context.get('default_res_id')) or lead_id
            if lead_id:
                check_demo(self.env['crm.lead'].browse(lead_id))
        return super().create(vals_list)
