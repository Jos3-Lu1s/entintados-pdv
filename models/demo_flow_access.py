"""Roles and record boundaries for CRM demonstrations only.

Global rules intersect native group rules. Additional read grants are restricted
to related demonstration documents; ordinary documents keep native permissions.
"""
from odoo import api, fields, models, _
from odoo.exceptions import AccessError
from odoo.fields import Domain


PREFIX = 'entintados_pdv.group_demo_'
PARENTS = {
    'crm.material.line': ('crm.lead', 'lead_id'),
    'calendar.event': ('crm.lead', 'crm_lead_id'),
    'approval.approver': ('approval.request', 'request_id'),
    'approval.product.line': ('approval.request', 'approval_request_id'),
    'stock.move': ('stock.picking', 'picking_id'),
    'stock.move.line': ('stock.picking', 'picking_id'),
}


def prefixed(domain, path):
    return domain.map_conditions(lambda term: Domain(path + '.' + term.field_expr, term.operator, term.value))


class DemoFlowUser(models.Model):
    _inherit = 'res.users'

    def _demo_flow_domains(self, model, operation):
        """Return (flow scope, permitted subset), without searching protected models."""
        self.ensure_one()
        crm, approval, audit = [self.has_group(PREFIX + role) for role in ('crm', 'approval', 'audit')]
        if model in PARENTS:
            parent, path = PARENTS[model]
            # Child rows can be removed by their editor; deleting whole flow
            # documents is deliberately disabled for the operational roles.
            scope, allowed = self._demo_flow_domains(parent, 'write' if operation in ('create', 'unlink') else operation)
            scope, allowed = prefixed(scope, path), prefixed(allowed, path)
            if model == 'approval.approver' and operation != 'read':
                allowed &= Domain('user_id', '=', self.id)
            return scope, allowed
        if model == 'crm.lead':
            scope = Domain('is_demo_flow', '=', True)
            own = Domain('user_id', '=', self.id) if crm else Domain.FALSE
            related = Domain.OR([
                Domain('demo_approval_ids.approver_ids.user_id', '=', self.id) if approval else Domain.FALSE,
                Domain('demo_approval_ids.material_auditor_ids.user_id', '=', self.id) if audit else Domain.FALSE,
            ])
            allowed = Domain.OR([own, related]) if operation == 'read' else own
        elif model == 'approval.request':
            scope = Domain('crm_lead_id', '!=', False) & Domain('category_id.approval_type', '=', 'stock_out')
            own = Domain('approver_ids.user_id', '=', self.id) if approval else Domain.FALSE
            related = Domain.OR([
                Domain('crm_lead_id.user_id', '=', self.id) if crm else Domain.FALSE,
                Domain('material_auditor_ids.user_id', '=', self.id) if audit else Domain.FALSE,
            ])
            allowed = Domain.OR([own, related]) if operation == 'read' else own
            if operation == 'create':
                allowed = Domain.FALSE  # Created exclusively by the CRM action.
        elif model == 'stock.picking':
            material_type = self.env.ref('entintados_pdv.picking_type_material_output', raise_if_not_found=False)
            scope = Domain('picking_type_id', '=', material_type.id if material_type else 0) & Domain.OR([
                Domain('crm_lead_id', '!=', False), Domain('approval_request_id.crm_lead_id', '!=', False)])
            own = Domain('approval_request_id.material_auditor_ids.user_id', '=', self.id) if audit else Domain.FALSE
            related = Domain.OR([
                Domain('crm_lead_id.user_id', '=', self.id) if crm else Domain.FALSE,
                Domain('approval_request_id.crm_lead_id.user_id', '=', self.id) if crm else Domain.FALSE,
                Domain('approval_request_id.approver_ids.user_id', '=', self.id) if approval else Domain.FALSE,
            ])
            allowed = Domain.OR([own, related]) if operation == 'read' else own
            if operation == 'create':
                allowed = Domain.FALSE  # Generated by the approval action.
        else:
            raise ValueError(model)
        if operation == 'unlink':
            allowed = Domain.FALSE
        return scope, allowed

    def _demo_flow_rule_domain(self, model, operation, grant=False):
        scope, allowed = self._demo_flow_domains(model, operation)
        if grant:
            # Read-only ACLs for cross-module consultation must not grant access
            # to native documents or documents belonging to other companies.
            company_path = PARENTS[model][1] + '.company_id' if model in PARENTS else 'company_id'
            return list(scope & allowed & Domain.OR([
                Domain(company_path, '=', False), Domain(company_path, 'in', self.env.companies.ids),
            ]))
        if not self.has_group(PREFIX + 'user'):
            return [(1, '=', 1)]
        return list(~scope | allowed)


def check_demo(records, operation='write'):
    """Check before public methods that may use sudo internally."""
    if not records.env.su and records.env.user.has_group(PREFIX + 'user'):
        records.check_access(operation)


def write_child(records, vals, write):
    check_demo(records)
    result = write(vals)
    check_demo(records)
    return result


class DemoFlowLead(models.Model):
    _inherit = 'crm.lead'

    is_demo_flow = fields.Boolean(compute='_compute_is_demo_flow', store=True, index=True)
    @api.depends('stage_type', 'demo_approval_ids', 'approval_request_id', 'crm_meeting_ids.crm_activity_type_id')
    def _compute_is_demo_flow(self):
        demo_type = self.env.ref('entintados_pdv.mail_activity_type_demo', raise_if_not_found=False)
        for lead in self:
            lead.is_demo_flow = bool(lead.stage_type == 'demo' or lead.demo_approval_ids or lead.approval_request_id
                                     or (demo_type and demo_type in lead.crm_meeting_ids.crm_activity_type_id))

    def action_request_material_output(self):
        check_demo(self)
        return super().action_request_material_output()

    def action_cancel_demo(self):
        check_demo(self)
        return super().action_cancel_demo()

    def write(self, vals):
        check_demo(self)
        result = super().write(vals)
        check_demo(self)  # Also check the resulting owner/scope after relinking.
        return result

class DemoFlowApproval(models.Model):
    _inherit = 'approval.request'

    def unlink(self):
        check_demo(self, 'unlink')
        return super().unlink()

    def action_approve(self, approver=None):
        check_demo(self)
        if approver and not self.env.su and self.env.user.has_group(PREFIX + 'user'):
            rows = approver if isinstance(approver, models.BaseModel) else self.env['approval.approver'].browse(approver)
            for row in rows:
                if row.request_id.crm_lead_id and row.request_id.category_id.approval_type == 'stock_out' and (row.request_id not in self or row.user_id != self.env.user):
                    raise AccessError(_('Solo puedes registrar tu propia aprobación.'))
        return super().action_approve(approver=approver)

    def action_refuse(self, approver=None):
        check_demo(self)
        return super().action_refuse(approver=approver)

    def action_reject_demo(self):
        check_demo(self)
        return super().action_reject_demo()

    def action_cancel(self):
        check_demo(self)
        return super().action_cancel()

    def action_confirm(self):
        check_demo(self)
        return super().action_confirm()

    def action_draft(self):
        check_demo(self)
        return super().action_draft()

    def action_withdraw(self, approver=None):
        check_demo(self)
        return super().action_withdraw(approver=approver)

    def write(self, vals):
        check_demo(self)
        if not self.env.su and self.env.user.has_group(PREFIX + 'user') and self.filtered(
                lambda request: request.crm_lead_id and request.category_id.approval_type == 'stock_out'):
            if {'crm_lead_id', 'category_id', 'request_owner_id', 'approver_ids'}.intersection(vals):
                raise AccessError(_('No puedes cambiar el origen ni los responsables de una aprobación de demostración.'))
        result = super().write(vals)
        check_demo(self)
        return result


